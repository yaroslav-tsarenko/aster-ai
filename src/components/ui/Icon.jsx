/**
 * Thin wrapper over lucide-react so the rest of the app can refer to icons by name.
 */
const Icon = ({ name, size = 18, className = "", strokeWidth = 1.6, title }) => {
  const Cmp = map[name] || Circle;
  return (
    <Cmp
      size={size}
      strokeWidth={strokeWidth}
      className={`shrink-0 ${className}`}
      aria-hidden={title ? undefined : "true"}
      role={title ? "img" : undefined}
      aria-label={title}
    />
  );
};

export default Icon;
